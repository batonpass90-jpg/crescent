import type { ContentCategory } from "./content-types";

export const SYSTEM_PROMPT = `당신은 한국 자취생을 위한 식단 인스타그램 카드뉴스 콘텐츠 작가입니다.

[독자]
- 20-30대 직장인/대학생, 1인 가구
- 작은 냉장고·1구 인덕션·기본 조리도구만 보유
- 시간·돈·에너지 모두 부족한 평일 저녁 식사 고민

[톤앤매너]
- 친근하고 가벼운 반말체 ("~해봐", "~지", "~잖아", "~거든")
- 솔직하고 실용적, 과장 광고 금지 ("최고의", "무조건 먹어야" 등 X)
- 실패담·현실 인정 환영 ("귀찮으면 그냥 ~로 때워도 돼")
- 영양/건강 정보는 검증 가능한 수준에서만 (의학적 효능 단정 금지)

[필수 출력 구조]
- title: 메인 카피 (15자 이내, 클릭 유발)
- cards: 정확히 5장
  - headline: 카드 제목 (12자 이내)
  - body: 본문 (한국어 100자 이내). 재료/리스트/단계는 한 줄에 한 항목씩 줄바꿈(\n)으로 구분하고 "· " 또는 "1. " prefix 사용. 일반 문장은 1-2문장.
  - image_concept: 이미지 시각 컨셉 (영문 또는 한글, 카드 제작용 시각 묘사 50자 이내, 예: "흰 그릇에 담긴 김치볶음밥, 위에서 본 컷, 따뜻한 색감")
- caption: 인스타 캡션 (250자 이내, 첫 줄에 후킹, 줄바꿈 적극 사용)
- hashtags: 5-10개 (#자취식단 #자취요리 #1인가구 등 카테고리 적합)

[금지]
- 의학적 효능/치료 단정
- 특정 브랜드/매장 광고
- 다이어트 강박, 체중 압박, 외모 평가
- "AI가 추천하는" 같은 메타적 표현
- 카드 5장 이외의 개수`;

export function buildUserPrompt(
  category: ContentCategory,
  dateISO: string,
): string {
  const date = new Date(dateISO);
  const weekday = ["일", "월", "화", "수", "목", "금", "토"][date.getDay()];
  const dateLabel = `${date.getMonth() + 1}월 ${date.getDate()}일 (${weekday})`;

  switch (category) {
    case "weekly_menu":
      return `${dateLabel} 기준 주간 자취 식단표 카드뉴스를 만들어줘.

5장 구성 가이드:
1. 인트로/이번 주 컨셉 (예: "이번 주는 단백질 위주", "냉장고 비우기 주간")
2. 월·화·수 식단 (한 줄씩)
3. 목·금 식단 + 주말 자유식 가이드
4. 장보기 리스트 (1주 예산·재료)
5. 자취 꿀팁 (이번 주 메뉴와 연결된 보관/재활용 팁)

영양 균형, 가성비, 자취 친화도(쉬운 조리)를 모두 고려해줘.`;

    case "diet_info":
      return `${dateLabel} 자취생을 위한 식단 정보 카드뉴스를 만들어줘.

5장 구성:
1. 후킹 질문/문제 제기 ("자취하면서 이거 헷갈리지?")
2. 핵심 정보 1
3. 핵심 정보 2
4. 자취 상황에 적용하는 법
5. 한 줄 요약 + 행동 제안

주제는 자취생이 헷갈리거나 모를 만한 한 가지(예: 단백질 보충 / 야식 대안 / 식재료 보관 / 도시락 영양 / 외식 vs 집밥 비교 등)를 골라 구체적으로. 광고성 금지.`;

    case "today_meal":
      return `${dateLabel} 오늘의 자취 한 끼 카드뉴스를 만들어줘.

5장 구성:
1. 오늘 메뉴 소개 (이름 + 한 줄 후킹)
2. 재료 (1인분 기준, 마트에서 구할 수 있는 것만)
3. 조리 STEP 1-2
4. 조리 STEP 3-4 (완성)
5. 마무리 팁 (남은 재료 활용 / 변형 / 보관)

30분 내, 1구 인덕션으로 가능한 메뉴여야 함.`;
  }
}
